#!/usr/bin/env node
/**
 * tools/build-js.mjs
 *
 * THE PROBLEM
 * index/menu/about/visit shipped React's development build plus
 * @babel/standalone from unpkg (~900 KB compressed) and compiled ~100 KB of JSX
 * on the visitor's phone before drawing anything. Lighthouse mobile on
 * 09.10.2026: first paint 8.8 s, LCP 15.4 s, score 35. A guest tapping
 * "Website" in Google Maps looked at an empty tiled page long enough to think
 * the site was down.
 *
 * THE FIX
 * Compile once here with the same @babel/standalone version and the same
 * options the browser used for <script type="text/babel"> (presets react + env,
 * three plugins, no targets - see transformScriptTags in babel.min.js), so the
 * code that runs is the code that ran before, only it arrives finished. React's
 * production UMD build is served from signa.cafe itself: the connection to the
 * host is already open, unpkg would cost another DNS + TCP + TLS from Bali.
 *
 *   js/react.js   React + ReactDOM 18.3.1 production (never changes)
 *   js/core.js    tweaks-panel, stickers, sections, site - shared by all pages
 *   js/<page>.js  page entry: app.jsx for home, page-*.jsx for the rest
 *
 * Files are concatenated, not wrapped: Babel turns top-level const into var,
 * so every file still shares one global scope, exactly as separate script tags
 * did. React stays in its own file because it is sloppy-mode code, and gluing
 * it in front would cancel the "use strict" Babel puts on top of ours.
 *
 * The block between JS-BUNDLE markers in each page is rewritten with content
 * hashes (?v=), and .htaccess caches /js/ for a year as immutable.
 *
 *   npm run build          compile + rewrite the four pages
 *   npm run build:check    exit 1 if js/ or a page is stale (deploy guard)
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const Babel = require("@babel/standalone");
const esbuild = require("esbuild");

const CHECK = process.argv.includes("--check");

const CORE = ["tweaks-panel", "stickers", "sections", "site"];
const PAGES = {
  "index.html": { entry: "app", out: "home" },
  "about.html": { entry: "page-about", out: "about" },
  "menu.html": { entry: "page-menu", out: "menu" },
  "visit.html": { entry: "page-visit", out: "visit" },
};

// Same options @babel/standalone 7.29.0 builds for a text/babel script tag
// without data-presets / data-plugins / data-targets.
const BABEL_OPTS = {
  presets: ["react", "env"],
  plugins: ["transform-class-properties", "transform-object-rest-spread", "transform-flow-strip-types"],
  targets: { browsers: undefined },
  sourceMaps: false,
};

const read = (p) => readFileSync(join(ROOT, p), "utf8");
const hash = (s) => createHash("sha1").update(s).digest("hex").slice(0, 10);

function compile(names) {
  const code = names
    .map((n) => Babel.transform(read(`src/${n}.jsx`), { ...BABEL_OPTS, filename: `src/${n}.jsx` }).code)
    .join(";\n");
  // target keeps the minifier from introducing syntax newer than ES2015.
  return esbuild.transformSync(code, { minify: true, legalComments: "none", target: "es2015" }).code;
}

const files = {
  "js/react.js": [
    read("node_modules/react/umd/react.production.min.js"),
    read("node_modules/react-dom/umd/react-dom.production.min.js"),
  ].join("\n"),
  "js/core.js": compile(CORE),
};
for (const { entry, out } of Object.values(PAGES)) files[`js/${out}.js`] = compile([entry]);

const BEGIN = "<!-- JS-BUNDLE:BEGIN (generated by tools/build-js.mjs - edit src/*.jsx, then npm run build) -->";
const END = "<!-- JS-BUNDLE:END -->";

// content.json is requested right here, while the scripts download, instead of
// after they run. site.jsx hydrateContent() picks the promise up.
const block = (out) =>
  [
    BEGIN,
    `<script>try{window.__signaContent=fetch("content.json",{cache:"no-store"}).catch(function(){return null})}catch(e){}</script>`,
    ...["react", "core", out].map((f) => `<script defer src="js/${f}.js?v=${hash(files[`js/${f}.js`])}"></script>`),
    END,
  ].join("\n");

const pages = {};
for (const [page, { out }] of Object.entries(PAGES)) {
  const html = read(page);
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${page}: JS-BUNDLE markers not found`);
  pages[page] = html.slice(0, a) + block(out) + html.slice(b + END.length);
}

const outputs = { ...files, ...pages };
const stale = Object.keys(outputs).filter((p) => !existsSync(join(ROOT, p)) || read(p) !== outputs[p]);

if (CHECK) {
  if (stale.length) {
    console.error(`stale build output: ${stale.join(", ")}\nrun: npm run build`);
    process.exit(1);
  }
  console.log("build output is up to date");
  process.exit(0);
}

mkdirSync(join(ROOT, "js"), { recursive: true });
for (const p of stale) writeFileSync(join(ROOT, p), outputs[p]);
for (const p of Object.keys(files)) console.log(`  ${p}  ${(outputs[p].length / 1024).toFixed(1)} KB`);
console.log(stale.length ? `updated: ${stale.join(", ")}` : "nothing changed");
